const severityRank = { critical: 0, high: 1, medium: 2 };

export function compareFindingPriority(a, b) {
  return (severityRank[a.severity] ?? 3) - (severityRank[b.severity] ?? 3)
    || (b.weight ?? 0) - (a.weight ?? 0)
    || (a.clauseIndex ?? 0) - (b.clauseIndex ?? 0);
}

function rule(id, docTypes, title, severity, weight, patterns, plainExplanation, actionTip, counterClause) {
  return { id, docTypes, title, severity, weight, patterns, plainExplanation, actionTip, counterClause };
}

